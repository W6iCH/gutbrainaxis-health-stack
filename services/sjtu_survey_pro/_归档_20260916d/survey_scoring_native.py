#  4. 原生映射：单条作答 → 分值
# ════════════════════════════════════════════════════════════════════════════
def item_score(item, strict=True, audit=None):
    """
    item 需含：question / answer_text / matrix / option_idx（矩阵题）
    返回 (score, source)；无法映射时：strict → 抛 UnmappedAnswer；否则 (None, reason) 并记审计。
    """
    q = item.get("question", "")
    ans = item.get("answer_text")
    mtx = item.get("matrix")
    idx = item.get("option_idx")

    if mtx and mtx in MATRIX_RULES and idx is not None:
        rule = MATRIX_RULES[mtx]
        v = rule["vmin"] + idx
        if q in rule["reverse"]:
            v = rule["vmin"] + rule["vmax"] - v
        return v, "matrix_option_index"

    rule_c = CHOICE_RULES.get(q)
    if rule_c is not None:
        if ans in rule_c:
            return rule_c[ans], "choice_label"
        reason = f"choice_label_unmapped:{q!r}:{ans!r}"
        if strict:
            raise UnmappedAnswer(reason)
        if audit is not None:
            audit.append({"question": q, "answer": ans, "reason": reason})
        return None, reason

    if q in NON_SCORING:
        return None, "not_scored"
    if mtx:
        reason = f"matrix_not_configured:{mtx!r}"
    else:
        reason = f"question_not_in_bank:{q!r}"
    if strict:
        raise UnmappedAnswer(reason)
    if audit is not None:
        audit.append({"question": q, "answer": ans, "reason": reason})
    return None, reason


