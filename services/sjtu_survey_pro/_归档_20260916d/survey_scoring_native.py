def compute_bmi(height_cm, weight_kg):
    h, w = _to_number(height_cm), _to_number(weight_kg)
    if not h or not w or h < 80 or h > 250 or w < 20 or w > 400:
        return None
    bmi = round(w / ((h / 100.0) ** 2), 1)
    cat = ("偏瘦" if bmi < 18.5 else "正常" if bmi < 24.0 else "超重" if bmi < 28.0 else "肥胖")
    return {"total": bmi, "category": cat}


def score_ipaq(ans_by_q):
    """MET-min/周 = 剧烈 8.0 + 中度 4.0 + 步行 3.3；截断：天 ≤7、单日 ≤180 分钟。"""
    def val(key):
        return _to_number(ans_by_q.get(IPAQ_ITEMS[key]))

    def clip(d, m):
        return max(0.0, min(d or 0.0, 7.0)), max(0.0, min(m or 0.0, 180.0))

    vd, vm = clip(val("vig_days"), val("vig_min"))
    md, mm = clip(val("mod_days"), val("mod_min"))
    wd, wm = clip(val("walk_days"), val("walk_min"))
    met = round(vd * vm * 8.0 + md * mm * 4.0 + wd * wm * 3.3)
    level = ("高体力活动水平" if met >= 3000 else
             "中等体力活动水平" if met >= 600 else "低体力活动水平")
    return {"total": met, "level": level, "vig": round(vd * vm * 8.0),
            "mod": round(md * mm * 4.0), "walk": round(wd * wm * 3.3),
            "sedentary_min": val("sit")}
