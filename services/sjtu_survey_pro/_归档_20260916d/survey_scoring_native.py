def _psqi_c5(freq_sum, n_items):
    cap = 3 * max(1, n_items)
    if freq_sum <= 0:
        return 0
    if freq_sum <= cap / 3.0:
        return 1
    if freq_sum <= cap * 2 / 3.0:
        return 2
    return 3


def _psqi_c7(a, b):
    s = a + b
    if s <= 0:
        return 0
    if s <= 2:
        return 1
    if s <= 4:
        return 2
    return 3


def _to_number(text):
    if text is None:
        return None
    m = re.search(r"-?\d+(?:\.\d+)?", str(text))
    return float(m.group(0)) if m else None


def score_all(ans_items, strict=True):
    """按原生口径计全部分值。返回 dict；strict=False 时附 `_audit` 审计行。"""
    by_q = {}
    for it in ans_items:
        by_q.setdefault(it.get("question", ""), []).append(it)
    audit = []

    def one(q):
        v = by_q.get(q)
        if not v:
            if strict:
                raise UnmappedAnswer(f"item_absent:{q!r}")
            audit.append({"question": q, "answer": None, "reason": "item_absent"})
            return None
        s, _ = item_score(v[0], strict=strict, audit=audit)
        return s

    def total_of(items):
        vals = [one(q) for q in items]
        vals = [v for v in vals if v is not None]
        return (sum(vals) if vals else None), vals

    out = {}
    t, v = total_of(GAD7_ITEMS)
    out["GAD-7"] = {"total": t, "n_items": len(v), "n_expected": 7, "max_score": 21,
                    "band": band(t, GAD7_BANDS)}
    t, v = total_of(PHQ9_ITEMS)
    out["PHQ-9"] = {"total": t, "n_items": len(v), "n_expected": 9, "max_score": 27,
                    "band": band(t, PHQ9_BANDS)}
    t, v = total_of(PSS_NONREV + PSS_REV)
    out["PSS-14"] = {"total": t, "n_items": len(v), "n_expected": 14, "max_score": 56,
                     "band": band(t, PSS14_BANDS)}
    t, v = total_of(GSRS_FLAT)
    out["GSRS"] = {"total": t, "n_items": len(v), "n_expected": 15, "max_score": 75,
                   "band": band(t, GSRS_BANDS_CUSTOM)}
    t, v = total_of(VSI_ITEMS)
    out["VSI"] = {"total": t, "n_items": len(v), "n_expected": 15, "max_score": 90,
                  "band": band(t, VSI_BANDS_CUSTOM), "normalized_0_90": (t - 15) if t is not None else None}

    sub = {}
    for comp, items in (("情绪性饮食", DEBQ_EMOTIONAL), ("外部性饮食", DEBQ_EXTERNAL),
                        ("限制性饮食", DEBQ_RESTRAINED)):
        vals = [one(q) for q in items]
        vals = [x for x in vals if x is not None]
        if vals:
            m = sum(vals) / len(vals)
            sub[comp] = {"sum": sum(vals), "mean": round(m, 2), "n_items": len(vals),
                         "n_expected": len(items), "band": band(m, DEBQ_LEVELS)}
    out["DEBQ"] = {"subscales": sub, "n_items": sum(s["n_items"] for s in sub.values()),
                   "n_expected": 33}

    dom = {}
    for dname, nums in WHOQOL_DOMAINS.items():
        vals = [one(WHOQOL_ITEMS[n]) for n in nums]
        vals = [x for x in vals if x is not None]
        if vals:
            m = sum(vals) / len(vals)
            dom[dname] = {"mean": round(m, 2), "score_4_20": round(m * 4, 2),
                          "score_0_100": round((m * 4 - 4) * 100 / 16, 1),
                          "n_items": len(vals), "n_expected": len(nums)}
    out["WHOQOL-BREF"] = {"domain_scores": dom,
                          "overall": {"总体生存质量": one(WHOQOL_ITEMS[1]),
                                      "总体健康状况": one(WHOQOL_ITEMS[2])}}

    comp = {"C1_主观睡眠质量": one(PSQI_C1)}
    lat, dis = one(PSQI_C2A), one(PSQI_C2B)
    if lat is None and dis is None:
        comp["C2_睡眠潜伏期"] = None
    else:
        s = (lat or 0) + (dis or 0)
        comp["C2_睡眠潜伏期"] = 0 if s <= 0 else (1 if s <= 2 else (2 if s <= 4 else 3))
    comp["C3_睡眠时长"] = one(PSQI_C3)
    comp["C4_睡眠效率"] = one(PSQI_C4)
    c5 = [one(q) for q in PSQI_C5_ITEMS]
    c5v = [x for x in c5 if x is not None]
    comp["C5_睡眠障碍"] = _psqi_c5(sum(c5v), len(c5v)) if c5v else None
    comp["C6_催眠药物"] = one(PSQI_C6)
    a7, b7 = one(PSQI_C7_A), one(PSQI_C7_B)
    comp["C7_日间功能障碍"] = (_psqi_c7(a7, b7) if (a7 is not None and b7 is not None)
                            else (_psqi_c7(a7, 0) if a7 is not None
                                  else (_psqi_c7(b7, 0) if b7 is not None else None)))
    keys = ["C1_主观睡眠质量", "C2_睡眠潜伏期", "C3_睡眠时长", "C4_睡眠效率",
            "C5_睡眠障碍", "C6_催眠药物", "C7_日间功能障碍"]
    avail = [comp[k] for k in keys if comp.get(k) is not None]
    tot = sum(avail) if avail else None
    out["PSQI"] = {"total": tot, "n_components": len(avail), "components": comp,
                   "band": ("睡眠质量差" if (tot or 0) > 7 else "睡眠质量尚可")}
    out["_audit"] = audit
    return out


